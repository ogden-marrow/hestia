#!/usr/bin/env python3
"""Write THIRD_PARTY.md: every crate that is built into Hestia on Linux, with its version and licence.
  python3 packaging/third-party.py           rewrite THIRD_PARTY.md
  python3 packaging/third-party.py --check   fail if THIRD_PARTY.md is out of date (CI)
The licences themselves are enforced separately by `cargo deny check licenses` (deny.toml)."""
import json, subprocess, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-unknown-linux-gnu"], cwd=root))
members = set(meta["workspace_members"])
rows = sorted({(p["name"], p["version"], p.get("license") or "(see crate)", p.get("repository") or "")
               for p in meta["packages"] if p["id"] not in members})
out = ["# Third-party components", "",
       "Hestia is MIT licensed (see LICENSE). It is built with the open-source crates below; each is used under the licence shown.",
       "Where a crate offers a choice (`OR`), Hestia uses the permissive alternative. This list is generated by",
       "`packaging/third-party.py` and checked in CI; the allowed licences are enforced by `cargo deny check licenses`.", "",
       f"{len(rows)} crates.", "", "| Crate | Version | Licence |", "|---|---|---|"]
out += [f"| {n} | {v} | {l} |" for n, v, l, _ in rows]
text = "\n".join(out) + "\n"
path = root / "THIRD_PARTY.md"
if "--check" in sys.argv:
    if not path.exists() or path.read_text() != text:
        sys.exit("THIRD_PARTY.md is out of date: run python3 packaging/third-party.py")
    print("THIRD_PARTY.md is current")
else:
    path.write_text(text); print(f"wrote {path.name}: {len(rows)} crates")
